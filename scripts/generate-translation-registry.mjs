import {readdir, readFile, writeFile} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const translationsDirectory = path.join(root, "src/content/translations");
const outputPath = path.join(root, "src/content/translation-registry.ts");
const checkOnly = process.argv.includes("--check");
const catalog = JSON.parse(
  await readFile(path.join(translationsDirectory, "catalog.json"), "utf8"),
);
const files = (await readdir(translationsDirectory))
  .filter((name) => name.endsWith(".json") && name !== "catalog.json")
  .sort();

const locales = files.map((fileName) => fileName.replace(/\.json$/, ""));
const expectedIds = new Set(catalog.entries.map((entry) => entry.id));
for (const [index, fileName] of files.entries()) {
  const locale = locales[index];
  const file = JSON.parse(
    await readFile(path.join(translationsDirectory, fileName), "utf8"),
  );
  const actualIds = Object.keys(file.translations ?? {});
  if (
    file.locale !== locale ||
    file.sourceHash !== catalog.sourceHash ||
    actualIds.length !== expectedIds.size ||
    actualIds.some((id) => !expectedIds.has(id))
  ) {
    throw new Error(`${fileName} is incomplete or stale; validate it before generating the registry.`);
  }
}
const variableName = (locale) => `locale_${locale.replaceAll("-", "_")}`;
const imports = locales
  .map((locale) => `import ${variableName(locale)} from "./translations/${locale}.json";`)
  .join("\n");
const entries = locales
  .map((locale) => `  ${JSON.stringify(locale)}: ${variableName(locale)},`)
  .join("\n");
const content = `/* This file is generated by scripts/generate-translation-registry.mjs. */
import type {SiteLocale} from "@/config/seo";
import type {LocaleTranslationFile} from "./translation-catalog";
${imports ? `\n${imports}` : ""}

export const GENERATED_TRANSLATION_FILES = {
${entries}
} as unknown as Partial<Record<SiteLocale, LocaleTranslationFile>>;
`;

if (checkOnly) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== content) {
    console.error("Translation registry is stale. Run npm run translation:registry.");
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, content, "utf8");
}
console.log(`${checkOnly ? "Checked" : "Generated"} translation registry for ${locales.length} locale(s).`);
